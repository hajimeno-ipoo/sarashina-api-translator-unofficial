import { copyFile, readFile } from "node:fs/promises";
import { dirname, join, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const sourceDirectory = dirname(fileURLToPath(import.meta.url));
const root = dirname(sourceDirectory);
const output = join(root, "speech-status.bundle.js");
const licenses = new Map();

for (const name of ["react", "react-dom", "scheduler", "border-beam", "thinking-orbs", "voice-glow"]) {
  const license = (await readFile(join(sourceDirectory, "node_modules", name, "LICENSE"), "utf8")).trim();
  const names = licenses.get(license) ?? [];
  names.push(name);
  licenses.set(license, names);
}

const notices = [...licenses].map(([license, names]) => `${names.join(", ")}\n\n${license}`);
const shadowStylePackages = ["border-beam", "voice-glow"]
  .map(name => join(sourceDirectory, "node_modules", name) + sep);

// Safari can reject a <style> injected into a shadow root by a content script
// when the page has a restrictive CSP (WebKit bug 291734).
const shadowStylePlugin = {
  name: "speech-status-shadow-style",
  setup(build) {
    build.onResolve({ filter: /^react\/jsx-runtime$/ }, ({ importer }) => {
      if (shadowStylePackages.some(directory => importer.startsWith(directory))) {
        return { path: join(sourceDirectory, "shadow-style-runtime.js") };
      }
    });
  }
};

await build({
  entryPoints: [join(sourceDirectory, "index.jsx")],
  outfile: output,
  bundle: true,
  format: "iife",
  minify: true,
  target: ["chrome109", "safari15.6"],
  jsx: "automatic",
  plugins: [shadowStylePlugin],
  define: { "process.env.NODE_ENV": '"production"' },
  banner: {
    js: `/* Generated by npm run build --prefix speech-status. */\n/*!\n${notices.join("\n\n")}\n*/`
  }
});
await copyFile(output, join(root, "safari", "speech-status.bundle.js"));
await copyFile(join(root, "speech-captions.js"), join(root, "safari", "speech-captions.js"));
